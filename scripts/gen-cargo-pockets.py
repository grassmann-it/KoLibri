#!/usr/bin/env python3
# Generates src/KoLibri.Daily/CargoPocketData.g.cs from KoLmafia cultshorts.txt (BSD) and external/kolmafia-data/items.jsonl.
# Usage: python3 scripts/gen-cargo-pockets.py CULTSHORTS_TXT ITEMS_JSONL OUT_CS
import json, re, sys
cult, items_jsonl, out = sys.argv[1:4]
items = {}
for line in open(items_jsonl):
    o = json.loads(line)
    items.setdefault(o['name'].lower(), o)
ITEM_TYPES = {'Item','Item2','Avatar','Bell','Booze','Cash','Chess','Choco','Food','Fruit','Oyster','Potion','Yeg'}
rows = []
missing = []
for line in open(cult, encoding='utf-8'):
    if line.startswith('#') or not line.strip(): continue
    f = line.rstrip('\n').split('\t')
    if not f[0].isdigit() or len(f) < 2: continue
    pocket, typ = int(f[0]), f[1]
    rest = [x for x in f[2:] if x.strip()]
    if typ in ITEM_TYPES:
        its = []
        for r in rest:
            m = re.match(r'^(.*?)\s*\((\d+)\)$', r.strip())
            name, qty = (m.group(1), int(m.group(2))) if m else (r.strip(), 1)
            o = items.get(name.lower())
            if o is None: missing.append((pocket, name)); continue
            its.append((int(o['id']), o['name'], qty, 't' in o.get('accessFlags', []), int(o.get('autosell') or 0)))
        rows.append((pocket, typ, its, 0, None, None))
    elif typ == 'Meat':
        rows.append((pocket, typ, [], int(rest[0]), None, None))
    elif typ == 'Monster':
        rows.append((pocket, typ, [], 0, rest[0], None))
    else:
        rows.append((pocket, typ, [], 0, None, ', '.join(rest)[:60]))
def cs(s): return '"' + s.replace('\\','\\\\').replace('"','\\"') + '"'
with open(out, 'w', encoding='utf-8') as w:
    w.write('// <auto-generated>\n// Generated from KoLmafia src/main/resources/data/cultshorts.txt (BSD 3-Clause) and external/kolmafia-data/items.jsonl\n')
    w.write('// (item id, tradeable flag "t", autosell). Regenerate: python3 scripts/gen-cargo-pockets.py <kolmafia>/src/main/resources/data/cultshorts.txt external/kolmafia-data/items.jsonl src/KoLibri.Daily/CargoPocketData.g.cs\n// </auto-generated>\n')
    w.write('namespace KoLibri.Daily;\n\ninternal static class CargoPocketData\n{\n    public static readonly CargoPocket[] All =\n    {\n')
    for pocket, typ, its, meat, monster, other in sorted(rows):
        it = ', '.join(f'new CargoPocketItem({i}, {cs(n)}, {q}, {"true" if t else "false"}, {a})' for i,n,q,t,a in its)
        w.write(f'        new({pocket}, {cs(typ)}, new CargoPocketItem[] {{ {it} }}, {meat}, {cs(monster) if monster else "null"}, {cs(other) if other else "null"}),\n')
    w.write('    };\n}\n')
print(len(rows), 'rows; missing:', missing, file=sys.stderr)
